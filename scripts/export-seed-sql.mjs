/**
 * Writes the catalogue as a plain .sql file.
 *
 * The seed script needs Node and a terminal. This does not: the output can be
 * pasted straight into Neon's web SQL editor, which is the difference between
 * "install a toolchain first" and "paste this, press Run" for whoever is
 * setting the site up.
 */
import fs from 'node:fs';
import { SEED_SONGS } from '../src/infrastructure/db/seed-data.ts';

const q = (value) =>
  value === null || value === undefined ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`;

const tagArray = (tags) =>
  tags.length === 0 ? "'{}'::reason_tag[]" : `ARRAY[${tags.map(q).join(',')}]::reason_tag[]`;

const out = [];

out.push('-- Feelyrics catalogue');
out.push(`-- ${SEED_SONGS.length} songs. Generated by scripts/export-seed-sql.mjs — do not edit by hand.`);
out.push('-- Safe to run more than once: each song is deleted and reinserted.');
out.push('');
out.push('BEGIN;');
out.push('');

for (const song of SEED_SONGS) {
  out.push(`-- ${song.artist} — ${song.title} (${song.source}->${song.target})`);
  out.push(`DELETE FROM songs WHERE slug = ${q(song.slug)};`);
  out.push('WITH new_song AS (');
  out.push('  INSERT INTO songs (slug, title, artist, source_language, target_language, engine_version, feel_profile, provenance, requested_by, validated_by)');
  out.push(
    `  VALUES (${q(song.slug)}, ${q(song.title)}, ${q(song.artist)}, ${q(song.source)}::language_code, ${q(song.target)}::target_language, ${q(song.engineVersion)}, ${q(song.feelProfile)}, ${q(song.provenance)}::lyrics_provenance, ${q(song.requestedBy)}, ${q(song.validatedBy)})`,
  );
  out.push('  RETURNING id');
  out.push('), new_sections AS (');
  out.push('  INSERT INTO sections (song_id, position, label)');
  out.push('  SELECT new_song.id, v.position, v.label FROM new_song, (VALUES');
  out.push(
    song.sections
      .map((section) => `    (${section.position}, ${q(section.label)})`)
      .join(',\n'),
  );
  out.push('  ) AS v(position, label)');
  out.push('  RETURNING id, position');
  out.push(')');
  out.push('INSERT INTO lines (section_id, position, original, rendering, note, tags)');
  out.push('SELECT new_sections.id, v.position, v.original, v.rendering, v.note, v.tags');
  out.push('FROM new_sections JOIN (VALUES');

  const lineRows = [];
  for (const section of song.sections) {
    for (const line of section.lines) {
      lineRows.push(
        `  (${section.position}, ${line.position}, ${q(line.original)}, ${q(line.rendering)}, ${q(line.note)}, ${tagArray(line.tags)})`,
      );
    }
  }
  out.push(lineRows.join(',\n'));
  out.push(') AS v(section_position, position, original, rendering, note, tags)');
  out.push('  ON v.section_position = new_sections.position;');
  out.push('');
}

// The first rows of the public request queue, so it is not an empty box on day one.
const REQUESTS = [
  ['Sebebi Yar', 'BLOK3'],
  ['Kayıp Kalp', 'BLOK3'],
  ['Çok Güzel Gülüyorsun', 'BLOK3 & Poizi'],
  ['Ah Be Manolya', 'Burak Bulut'],
  ['Toz Pembe', 'manifest'],
  ['karambol', 'Murda & Motive'],
  ['Gamsız Hayat', 'Candan Erçetin'],
  ['YIN YANG', 'Motive'],
];

const dedupe = (title, artist) =>
  `${title} ${artist}`
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();

out.push('-- Opening entries for the request queue');
for (const [title, artist] of REQUESTS) {
  out.push(
    `INSERT INTO song_requests (title, artist, targets, has_lyrics, status, dedupe_key)` +
      ` SELECT ${q(title)}, ${q(artist)}, ARRAY['en','es']::target_language[], false, 'lyrics-needed'::request_status, ${q(dedupe(title, artist))}` +
      ` WHERE NOT EXISTS (SELECT 1 FROM song_requests WHERE dedupe_key = ${q(dedupe(title, artist))});`,
  );
}

out.push('');
out.push('COMMIT;');
out.push('');

fs.writeFileSync('feelyrics-catalogue.sql', out.join('\n'));
console.error(`wrote feelyrics-catalogue.sql (${SEED_SONGS.length} songs)`);
